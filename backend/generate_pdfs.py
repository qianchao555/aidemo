"""
生成公司制度知识库 PDF 文档。
输出目录：src/main/resources/knoledge/
"""

import os
from fpdf import FPDF

OUT_DIR = "src/main/resources/knoledge"
FONT_TITLE = "C:/Windows/Fonts/simhei.ttf"   # 黑体 → 标题
FONT_BODY  = "C:/Windows/Fonts/simfang.ttf"  # 仿宋 → 正文

class PolicyPDF(FPDF):
    """中文制度/流程文档 PDF 生成器"""

    def __init__(self, doc_title, version, dept, effective_date):
        super().__init__()
        self.doc_title = doc_title
        self.version = version
        self.dept = dept
        self.effective_date = effective_date
        self.add_font("title_font", "", FONT_TITLE)
        self.add_font("body_font", "", FONT_BODY)
        self.set_auto_page_break(True, 25)

    # ── 排版辅助 ──

    def cover_page(self):
        """封面：文档名称、版本、生效日期、所属部门"""
        self.add_page()
        self.ln(60)
        self.set_font("title_font", "", 28)
        self.cell(0, 16, self.doc_title, new_x="LMARGIN", new_y="NEXT", align="C")
        self.ln(10)
        self.set_font("body_font", "", 14)
        info = [
            f"版本：{self.version}",
            f"生效日期：{self.effective_date}",
            f"所属部门：{self.dept}",
        ]
        for line in info:
            self.cell(0, 10, line, new_x="LMARGIN", new_y="NEXT", align="C")
        self.ln(8)
        self.set_font("body_font", "", 11)
        self.cell(0, 8, "（内部资料，请勿外传）", new_x="LMARGIN", new_y="NEXT", align="C")

    def chapter_title(self, text):
        """一级标题 —— 第一章 xxx"""
        self.ln(4)
        self.set_font("title_font", "", 16)
        self.cell(0, 10, text, new_x="LMARGIN", new_y="NEXT")
        self.ln(2)

    def section_title(self, text):
        """二级标题 —— 第一节 xxx"""
        self.set_font("title_font", "", 13)
        self.cell(0, 8, text, new_x="LMARGIN", new_y="NEXT")
        self.ln(1)

    def clause_title(self, text):
        """三级标题 —— 第N条 或 数字编号"""
        self.set_font("body_font", "", 12)
        self.cell(0, 8, text, new_x="LMARGIN", new_y="NEXT")

    def body(self, text):
        """正文段落"""
        self.set_font("body_font", "", 11)
        self.multi_cell(0, 7, text)
        self.ln(2)

    def step_title(self, text):
        """流程步骤标题 —— 第N步"""
        self.set_font("title_font", "", 13)
        self.cell(0, 9, text, new_x="LMARGIN", new_y="NEXT")
        self.ln(1)


