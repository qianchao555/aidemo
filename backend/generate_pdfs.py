    pdf.body("角色：人力资源部培训专员")
    pdf.body("时限：入职后一周内")

    pdf.body("所需材料汇总：")
    pdf.body("（1）身份证原件及复印件；（2）学历学位证书原件及复印件；（3）一寸照片2张；（4）离职证明；（5）体检报告；（6）银行卡复印件。")
    pdf.body("注意事项：如入职当天材料不齐全，可于入职后3个工作日内补交至人力资源部。逾期未补交的，暂缓签订劳动合同。")

    pdf.output(os.path.join(OUT_DIR, "入职办理流程.pdf"))
    print("[OK] 入职办理流程.pdf")


