# 7. 请休假申请流程（流程类文档）
# ═══════════════════════════════════════

def build_leave_process():
    pdf = PolicyPDF("请休假申请流程", "V1.8", "人力资源部", "2025-01-01")
    pdf.cover_page()

    pdf.chapter_title("请休假申请操作指引")

    pdf.body("适用场景：本流程适用于全体员工申请各类假期（年假/病假/婚假/产假/事假/丧假等）。")
    pdf.body("适用对象：全体在册员工")

    pdf.step_title("第1步：登录OA系统")
    pdf.body('员工登录公司OA办公系统（https://oa.company.com），进入「员工自助→考勤管理→请假申请」模块，点击「新建请假申请」。')
    pdf.body("角色：员工本人")
    pdf.body("时限：请假生效日前完成提交")

    pdf.step_title("第2步：填写请假信息")
    pdf.body("在请假申请表单中填写以下信息：\n（1）请假类型（年假/病假/事假/婚假/产假/丧假/其他）；\n（2）请假起止时间（精确到半天）；\n（3）请假事由（简要说明）；\n（4）紧急联系人及联系电话；\n（5）工作交接人及交接事项。")
    pdf.body("角色：员工本人")
    pdf.body("时限：约5分钟")

    pdf.step_title("第3步：上传证明材料")
    pdf.body("根据请假类型上传相应证明材料：\n（1）病假：二级及以上医院病假证明及诊断材料；\n（2）婚假：结婚证复印件；\n（3）产假：医院出具的相关证明；\n（4）事假及年假：无需证明材料。")
    pdf.body("角色：员工本人")
    pdf.body("所需材料：病假证明、结婚证复印件、产假证明等")

    pdf.step_title("第4步：直属领导审批")
    pdf.body("请假申请提交后，系统自动推送审批通知至直属领导。直属领导在OA系统中审核请假申请，确认工作交接安排合理后予以审批。审批通过则进入下一步，审批驳回则退回至员工修改后重新提交。")
    pdf.body("角色：直属领导")
    pdf.body("时限：1个工作日内完成审批")

    pdf.step_title("第5步：部门负责人审批（如需）")
    pdf.body("连续请假3天以上的，系统自动推送至部门负责人进行二次审批。部门负责人综合考虑部门工作安排后予以审批。连续请假5天以上的，还需人力资源部审批。")
    pdf.body("角色：部门负责人")
    pdf.body("时限：1个工作日内完成审批")

    pdf.step_title("第6步：人力资源部备案")
    pdf.body("审批全部完成后，系统自动将请假信息推送至人力资源部备案。人力资源部更新考勤系统中的请假记录，并计算可用假期余额。员工可在OA系统中查看审批进度和假期余额。")
    pdf.body("角色：人力资源部考勤专员")
    pdf.body("时限：自动备案")

    pdf.body("审批权限汇总：")
    pdf.body("（1）请假1天以内：直属领导审批即可；")
    pdf.body("（2）请假1-3天：直属领导 → 部门负责人审批；")
    pdf.body("（3）请假3天以上：直属领导 → 部门负责人 → 人力资源部审批。")
    pdf.body("注意事项：紧急请假的，可先通过电话或即时通讯工具口头请示直属领导，事后3个工作日内补交OA请假申请及相关材料。但事后补假不得超过3次/年。")

    pdf.output(os.path.join(OUT_DIR, "请休假申请流程.pdf"))
    print("[OK] 请休假申请流程.pdf")


