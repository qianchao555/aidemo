def build_travel_policy():
    pdf = PolicyPDF("差旅报销规定", "V2.3", "财务部", "2025-04-01")
    pdf.cover_page()

    pdf.chapter_title("第一章 总则")
    pdf.clause_title("第一条 目的与范围")
    pdf.body("为规范公司差旅管理，合理控制差旅费用，保障出差人员工作与生活需要，特制定本规定。本规定适用于公司全体员工因公出差的差旅申请及费用报销。")

    pdf.chapter_title("第二章 交通标准")
    pdf.clause_title("第二条 交通工具选择")
    pdf.body("高铁行程3小时以内的，乘坐二等座或硬卧；行程3-8小时的，乘坐一等座或硬卧；行程超过8小时的，可乘坐飞机经济舱。特殊情况需乘坐商务舱或一等座的，须经分管副总经理审批。")
    pdf.clause_title("第三条 市内交通")
    pdf.body("出差期间的市内交通以公共交通为主，据实报销。特殊情况需乘坐出租车的，须注明事由并经直属领导审批。出差目的地有公司签约网约车服务的，优先使用签约平台叫车。")
