    pdf.body("人力资源部在HR系统中录入新员工信息，IT部门开通以下系统账号：\n（1）企业邮箱账号；\n（2）OA办公系统账号；\n（3）考勤系统账号。\n账号初始密码为身份证后6位，首次登录须修改密码。")
