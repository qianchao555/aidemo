def build_leave_policy():
    pdf = PolicyPDF("请假制度", "V2.1", "人力资源部", "2025-01-01")
    pdf.cover_page()

    pdf.chapter_title("第一章 总则")
    pdf.clause_title("第一条 目的与依据")
    pdf.body("为规范员工请假管理，保障员工休息休假权利，根据《劳动法》《职工带薪年休假条例》等法律法规，结合公司实际，制定本制度。")
    pdf.clause_title("第二条 适用范围")
    pdf.body("本制度适用于公司全体在册员工。实习生请假参照事假条款执行。")

    pdf.chapter_title("第二章 年假")
    pdf.clause_title("第三条 年假计算标准")
    pdf.body("员工累计工作已满1年不满10年的，年休假5天；已满10年不满20年的，年休假10天；已满20年的，年休假15天。新入职员工当年年假按实际工作月份折算。")
    pdf.clause_title("第四条 年假申请与审批")
    pdf.body("年假须提前3个工作日通过OA系统提交请假申请，经直属领导审批。连续请年假3天以上须经部门负责人审批。年假最小请假单位为半天。")
    pdf.clause_title("第五条 年假有效期")
    pdf.body("当年年假应在当年12月31日前使用完毕，过期不补。因工作原因无法休完的，可延期至次年3月31日，须经部门负责人审批同意。")

    pdf.chapter_title("第三章 病假")
    pdf.clause_title("第六条 病假申请条件")
    pdf.body("员工因病或非因工负伤需要治疗休养的，可申请病假。病假须提供二级及以上医院出具的病假证明及诊断材料，包括门诊病历或住院证明。紧急情况可在恢复后3个工作日内补交。")
    pdf.clause_title("第七条 病假期间待遇")
    pdf.body("病假在1个月以内的，按本人基本工资的80%发放；超过1个月不满6个月的，按60%发放；超过6个月的，按当地最低工资标准发放，直至医疗期满。")
    pdf.clause_title("第八条 医疗期规定")
    pdf.body("医疗期根据员工实际工作年限和在本单位工作年限确定：实际工作年限10年以下的，在本单位工作年限5年以下的为3个月，5年以上的为6个月。超过医疗期仍不能胜任工作的，公司可依法解除劳动合同。")

    pdf.chapter_title("第四章 婚假与产假")
    pdf.clause_title("第九条 婚假")
    pdf.body("员工结婚可享受婚假3天。符合晚婚条件的（男25周岁以上，女23周岁以上），增加婚假7天，合计10天。婚假应在结婚登记后6个月内一次性使用。申请婚假须提供结婚证复印件。")
    pdf.clause_title("第十条 产假与陪产假")
    pdf.body("女员工生育享受产假98天（含产前15天），难产的增加15天，多胞胎每多生育1个婴儿增加15天。符合计划生育政策的，另享受奖励假80天。男员工配偶生育的，可享受陪产假15天。")

    pdf.chapter_title("第五章 事假与其他假期")
    pdf.clause_title("第十一条 事假")
    pdf.body("员工因私事需要处理的，可申请事假。事假每年累计不得超过15天，单次不超过5天。事假期间不计发工资，且事假累计超过10天的，当年不再享受年休假。")
    pdf.clause_title("第十二条 丧假")
    pdf.body("员工直系亲属（父母、配偶、子女）去世的，给予丧假3天；旁系亲属（祖父母、外祖父母、兄弟姐妹）去世的，给予丧假1天。丧假期间工资照发。")
    pdf.clause_title("第十三条 工伤假")
    pdf.body("员工因工负伤的，经劳动保障行政部门认定为工伤后，按照国家《工伤保险条例》规定享受工伤医疗期待遇，停工留薪期一般不超过12个月。")

    pdf.chapter_title("第六章 请假流程与违规处理")
    pdf.clause_title("第十四条 请假通用流程")
    pdf.body("所有假期均须通过OA系统提交请假申请，按以下审批权限执行：1天以内由直属领导审批；1-3天由直属领导+部门负责人审批；3天以上由部门负责人+人力资源部审批。")
    pdf.clause_title("第十五条 未请假或擅离职守")
    pdf.body("未按规定办理请假手续擅自离岗的，按旷工处理。连续旷工3天或年度累计旷工5天以上的，视为严重违反公司规章制度，公司有权解除劳动合同且不支付经济补偿。")

    pdf.chapter_title("第七章 附则")
    pdf.clause_title("第十六条 制度衔接")
    pdf.body("本制度未尽事宜，参照国家法律法规和公司其他相关制度执行。本制度自2025年1月1日起生效。")

    pdf.output(os.path.join(OUT_DIR, "请假制度.pdf"))
    print("[OK] 请假制度.pdf")


