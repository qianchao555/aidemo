    pdf.step_title("第4步：办公设备与工位分配")
    pdf.body("IT部门发放办公电脑及周边设备（显示器、键盘、鼠标），行政部分配工位、储物柜钥匙及办公文具。工位分配以部门集中为原则，便于团队协作。")
    pdf.body("角色：IT运维人员 + 行政专员")
    pdf.body("时限：约30分钟")

    pdf.step_title("第5步：入职培训安排")
