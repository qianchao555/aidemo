def build_code_of_conduct():
    pdf = PolicyPDF("行为规范", "V1.5", "行政部", "2025-01-01")
    pdf.cover_page()

    pdf.chapter_title("第一章 总则")
    pdf.clause_title("第一条 目的")
    pdf.body("为营造良好的工作环境，维护公司良好形象，保障公司正常经营秩序，依据相关法律法规及公司章程，制定本行为规范。")

    pdf.chapter_title("第二章 职业操守")
    pdf.clause_title("第二条 忠诚义务")
    pdf.body("员工应当对公司保持忠诚，不得利用公司资源和职务便利谋取个人利益或为他人谋取不正当利益。未经公司批准，不得在其他单位兼职或从事与公司业务存在竞争关系的活动。")
    pdf.clause_title("第三条 廉洁从业")
    pdf.body("员工不得收受业务往来单位或个人赠送的现金、有价证券、贵重物品或接受可能影响公正履职的宴请和招待。无法拒收的礼品，应按公司规定及时上交登记。")
    pdf.clause_title("第四条 利益冲突")
    pdf.body("员工如与公司供应商、客户或其他合作伙伴存在亲属关系或经济利益的，应主动向公司申报。涉及利益冲突的事项，员工应申请回避。")

    pdf.chapter_title("第三章 保密义务")
    pdf.clause_title("第五条 保密信息定义")
    pdf.body("公司保密信息包括但不限于：技术资料、经营数据、客户信息、供应商信息、薪酬数据、战略规划、合同条款、未公开的人事任免等。")
    pdf.clause_title("第六条 保密要求")
    pdf.body("员工在职期间及离职后两年内，不得以任何形式泄露或使用公司保密信息。不得在公共场所谈论公司机密事项，不得通过非公司授权的通讯工具传输保密信息。离职时须归还所有包含公司信息的文件、设备和账号。")
    pdf.clause_title("第七条 违反保密义务的责任")
    pdf.body("违反保密义务的，公司有权追究其法律责任，包括但不限于赔偿经济损失、承担违约金等。情节严重构成犯罪的，移交司法机关处理。")

    pdf.chapter_title("第四章 职场行为")
    pdf.clause_title("第八条 尊重与包容")
    pdf.body("公司倡导尊重、包容、平等的职场文化。严禁基于性别、年龄、民族、宗教信仰、性取向等因素的歧视行为。严禁职场性骚扰，一经查实，公司将严肃处理直至解除劳动合同。")
    pdf.clause_title("第九条 沟通与协作")
    pdf.body("员工之间应保持开放、坦诚的沟通，积极配合团队工作，不推诿、不扯皮。工作中出现分歧应通过正常沟通渠道解决，不得因私人矛盾影响正常工作。")
    pdf.clause_title("第十条 网络安全")
    pdf.body("员工不得在工作电脑上安装未经授权的软件，不得访问非法网站或下载盗版内容。严禁利用公司网络从事违法违规活动，包括但不限于网络赌博、非法集资、散布谣言等。")
    pdf.clause_title("第十一条 办公环境管理")
    pdf.body("员工应自觉维护办公环境的整洁和安静，不得在办公区域吸烟（指定吸烟区除外），不得在办公时间内大声喧哗或进行与工作无关的娱乐活动。")

    pdf.chapter_title("第五章 违纪处理")
    pdf.clause_title("第十二条 违纪等级")
    pdf.body("违纪行为分为三级：一般违纪（口头警告、书面警告）、严重违纪（记过、降职降薪）、重大违纪（解除劳动合同）。违纪处理应遵循事实清楚、证据确凿、程序合规的原则。")
    pdf.clause_title("第十三条 申诉机制")
    pdf.body("员工对违纪处分有异议的，可在收到处分通知后10个工作日内向人力资源部提出书面申诉。人力资源部应在15个工作日内组织调查并回复申诉结果。")

    pdf.chapter_title("第六章 附则")
    pdf.clause_title("第十四条 解释与修订")
    pdf.body("本规范由行政部负责解释，经总经理审批后生效。公司可根据实际情况进行修订，修订内容向全体员工公告。本规范自2025年1月1日起生效。")

    pdf.output(os.path.join(OUT_DIR, "行为规范.pdf"))
    print("[OK] 行为规范.pdf")


