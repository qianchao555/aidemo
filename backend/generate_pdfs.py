    pdf.body("因工作需要自驾出差的，油费和过路费据实报销，按实际行驶里程给予每公里1.2元的车辆损耗补贴。自驾出差须提前报备车辆信息。")

    pdf.chapter_title("第三章 住宿与餐饮")
